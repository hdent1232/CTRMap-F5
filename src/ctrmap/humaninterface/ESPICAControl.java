	public void runProcess(String ESPICAPath, ESPICAProcess proc) {
		output.setText(null);
		status.setText("Initializing");
		if (System.getProperty("os.name").startsWith("Windows")) {
			if (new File(ESPICAPath).canExecute()) {
				Thread ESPICAThread = new Thread() {
					public void run() {
						//THIS THREAD RUNS THE PROCESS AND READS IT; every widget write is handed
						//to the event thread (F220). It wrote the label, the log and the button
						//itself, while the event thread painted them.
						javax.swing.SwingUtilities.invokeLater(() -> status.setText("ESPICA running"));
						try {
							//ONE ARGUMENT PER PATH (F245): this was exec(path + " -i " + input ...), one string
							//split on whitespace, so a converter, OBJ, donor or output under a folder with a
							//space in its name - a Windows user folder, most of them - was handed in pieces
							Process process = new ProcessBuilder(proc.command(ESPICAPath)).start();
							InputStream is = process.getInputStream();
							InputStreamReader isr = new InputStreamReader(is);
							BufferedReader br = new BufferedReader(isr);
							String line;

							while ((line = br.readLine()) != null) {
								final String said = line + "\n";
								javax.swing.SwingUtilities.invokeLater(() -> output.append(said));
							}
							javax.swing.SwingUtilities.invokeLater(() -> {
								status.setText("ESPICA has finished");
								btnClose.setEnabled(true);
								isSuccess = true;
							});
						} catch (IOException ex) {
							//SAID, AND THE WINDOW LET GO (F206): this was logged and nothing else, so a
							//converter that would not start left "ESPICA running" up and Close disabled
							final String why = ctrmap.util.Bytes.reason(ex);
							javax.swing.SwingUtilities.invokeLater(() -> {
								status.setText("Failed - ESPICA could not run: " + why);
								output.append("ESPICA could not run: " + why + "\n");
								btnClose.setEnabled(true);
							});
						}
					}
				};
				ESPICAThread.setDaemon(true); //the converter is its own process; this only reads it
				ESPICAThread.start();
			} else {
				status.setText("Failed - ESPICA path not set or invalid.");
				btnClose.setEnabled(true);
			}
		} else {
			status.setText("Failed - unsupported OS");
			btnClose.setEnabled(true);
		}
	}

	public static class ESPICAProcess {

		public ESPICAFunctionMode mode;
		public File input;
		public File donor;
		public File output;
		public String[] extra;

		public ESPICAProcess(ESPICAFunctionMode mode, File input, File donor, File output, String[] extra) {
			this.mode = mode;
			this.input = input;
			this.donor = donor;
			this.output = output;
			this.extra = extra;
		}

		public String getMode() {
			switch (mode) {
				case MODEL_CONVERT:
					return "objconvert";
				case TEXTURE_MERGE:
					return "texturemerge";
				default:
					return "";
			}
		}

		/**
		 * The converter's command line, program first, one element per argument - never joined - and
		 * each file as its absolute path, so ESPICA's working directory does not decide what it reads.
		 */
		public java.util.List<String> command(String program) {
			java.util.List<String> argv = new java.util.ArrayList<>();
			argv.add(program);
			argv.add(getMode());
			argv.add("-i");
			argv.add(input.getAbsolutePath());
			argv.add("-d");
			argv.add(donor.getAbsolutePath());
			if (output != null) {
				argv.add("-o");
				argv.add(output.getAbsolutePath());
			}
			argv.addAll(java.util.Arrays.asList(extra));
			return argv;
		}
	}

	public enum ESPICAFunctionMode {
		TEXTURE_MERGE,
		MODEL_CONVERT
	}

