	/** The zone table as a mass edit walks it: every slot, in order, the owner's copy. */
	private Zone[] allZones() {
		Zone[] zones = new Zone[loadedZone.count()];
		for (int i = 0; i < zones.length; i++) {
			zones[i] = loadedZone.at(i);
		}
		return zones;
	}

